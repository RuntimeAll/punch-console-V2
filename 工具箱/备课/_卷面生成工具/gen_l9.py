def qhtml(n, q, with_answers, spacer):
    h = [f'<div class="q"><span class="no">{n}．</span><span class="star">{"★" * q["d"]}</span>{q["stem"]}</div>']
    if q.get('fig'):
        h.append(q['fig'])
    if with_answers:
        if q.get('ansfig'):
            h.append(q['ansfig'])
        h.append(f'<div class="ansbox"><p><span class="lab">【答案】</span>{q["answer"]}</p>'
                 f'<p><span class="lab">【解析】</span>{q["analyze"]}</p></div>')
    else:
        h.append(f'<div class="{spacer}"></div>')
    return h


def build(with_answers):
    """观察物体专项卷 = 思维题（教具·小正方体，独立首页）＋ 观察物体 10＋1 题。
    课内同步段已移入 ../平四梯形专项/。"""
    title = '第9课 · 观察物体 · 专项'
    h = [f'<!DOCTYPE html><html><head><meta charset="utf-8"><title>{title}</title>'
         f'<style>{CSS}</style></head><body><div class="doc">']
    h.append(f'<h1>{title}</h1>')
    h.append(f'<div class="sub">2026年8月2日　思维题（动手搭）＋ 观察物体 10 题'
             f'{"　（教师用 · 含答案解析）" if with_answers else ""}</div>')

    h.append('<div class="sec">思维题 · 露在外面的面（<span style="font-size:12pt">动手：小正方体教具</span>）</div>')
    h.append('<div class="big">')
    for i, q in enumerate(SIWEI, 1):
        h += qhtml(i, q, with_answers, 'sp')
    h.append('</div>')

    h.append('<div class="sec newpage">观察物体</div><div class="tight">')
    n = 0
    for blk in ZX_BLOCKS:
        tip = f'　<span class="tip">{blk["tip"]}</span>' if with_answers else ''
        h.append(f'<div class="blk">【{blk["title"]}】{tip}</div>')
