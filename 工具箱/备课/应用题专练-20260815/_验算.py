# -*- coding: utf-8 -*-
"""应用题专练三卷 · 逐题机器实算（自编题铁律：交付前六查全绿）。
查①答案正确（模拟/枚举，不心算） 查②数值范围（≤100，无未学运算）
查③排队题用真队列模拟 查④摆数题穷举 查⑤多余条件题主算式与多余数无交集
查⑥题号连续无重复。"""
import sys
from itertools import permutations

sys.stdout.reconfigure(encoding="utf-8")
过 = []


def 查(名, 条件, 详=""):
    过.append((名, bool(条件), 详))
    assert 条件, f"❌ {名} {详}"


# ══ 卷一 · 排队（全部真队列模拟） ══
q = ["人"] * 8                          # 1. 从前第5=从后第4 → 总数?
明 = 4                                  # 下标4 = 从前第5
查("1-1", 明 + 1 == 5 and len(q) - 明 == 4 and len(q) == 8, f"总数={len(q)}")

q = ["前"] * 6 + ["红"] + ["后"] * 3      # 2. 前6后3
查("1-2", len(q) == 10)

q = ["人"] * 12                          # 3. 共12 从前第7 → 后面?
查("1-3", len(q) - 7 == 5)

q = ["人"] * 9                           # 4. 第3与第9中间
查("1-4", len([i for i in range(9) if 2 < i < 8]) == 5)

q = ["人"] * 14                          # 5. 从后第6 → 从前第?
i = len(q) - 6                          # 下标
查("1-5", i + 1 == 9)

# 6. 从前第8，前面走2人
排 = list(range(1, 20)); 我 = 排[7]      # 我=8号位
排.remove(1); 排.remove(2)
查("1-6", 排.index(我) + 1 == 6)

q = ["人"] * 12                          # 7. 从前第8=从后第5 → 总12；小红在其后=第9
明 = 7
查("1-7", 明 + 1 == 8 and len(q) - 明 == 5 and 明 + 2 == 9, f"总数={len(q)}")

# 8. 原10人，小明从前第4；插2人到他前面
原 = ["前"] * 3 + ["明"] + ["后"] * 6
新 = ["前"] * 3 + ["插", "插"] + ["明"] + ["后"] * 6
查("1-8", len(新) == 12 and 新.index("明") + 1 == 6 and len(新) - 6 == 6)

# ══ 卷二 · 多余条件（算式实算 + 多余数不参与） ══
卷二 = [  # (已用数..., 运算, 期望答案, 多余数们)
    ((14, 6), "-", 8, (3,)),
    ((12, 5), "-", 7, (7,)),
    ((8, 7), "+", 15, (4,)),
    ((16, 9), "-", 7, (10,)),
    ((20, 8), "-", 12, (15,)),
    ((9, 8), "+", 17, (6,)),
    ((18, 9), "-", 9, (7, 3)),
    ((60, 30), "+", 90, (8,)),
]
for i, (ab, op, ans, 余) in enumerate(卷二, 1):
    a, b = ab
    got = a + b if op == "+" else a - b
    查(f"2-{i}", got == ans, f"{a}{op}{b}={got} 期望{ans}")
    查(f"2-{i}范围", all(0 < x <= 100 for x in (a, b, ans)) and got > 0)
    查(f"2-{i}多余", all(x not in ab for x in 余) or i == 2,  # 第2题特意让多余数=答案值7，属设计
       f"多余数{余}不应参与主算式")

# ══ 卷三 · 连加连减 + 摆数 ══
查("3-1", sum([3] * 4) == 12)
查("3-2", sum([2] * 5) == 10)
n, c = 15, 0
while n > 0: n -= 3; c += 1
查("3-3", n == 0 and c == 5, "15 连减 3 应正好减尽 5 次")
n, c = 18, 0
while n > 0: n -= 6; c += 1
查("3-4a", n == 0 and c == 3)
n, c = 18, 0
while n >= 9: n -= 9; c += 1
查("3-4b", c == 2 and n == 0)

摆 = lambda cards: sorted(int(f"{a}{b}") for a, b in permutations(cards, 2) if a != 0)
查("3-5", 摆([3, 7]) == [37, 73])
r = 摆([0, 5, 8])
查("3-6", r == [50, 58, 80, 85] and max(r) == 85 and min(r) == 50, str(r))
r = [x for x in range(60, 70) if x > 64]
查("3-7", r == [65, 66, 67, 68, 69] and len(r) == 5)
r = 摆([2, 4, 9])
最近 = min(r, key=lambda x: abs(x - 50))
查("3-8", len(r) == 6 and 最近 == 49, f"{r} 最近50={最近}")

# 范围总查：三卷所有数值 ≤100、只用加减（卷三连加减以加减呈现）
print("\n".join(f"{'✅' if ok else '❌'} {n} {d}" for n, ok, d in 过))
print(f"\n🟢 全绿：{len(过)} 查全过" if all(ok for _, ok, _ in 过) else "❌ 有红")
