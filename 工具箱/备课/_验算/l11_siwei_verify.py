# -*- coding: utf-8 -*-
"""第11课思维题（梯形阵 × 等差数列）验算。
主线：小棒按等差摆成梯形阵 ⇒ (首项＋末项)×项数÷2 与梯形面积公式 (上底＋下底)×高÷2 同构。
三关全部**逐根累加**校核，不只套公式。"""
OK = []


def chk(tag, got, want):
    ok = got == want
    OK.append(ok)
    print(f"[{'PASS' if ok else 'FAIL'}] {tag}: got={got} want={want}")


def rows(first, diff, n):
    """逐行根数（不套求和公式）。"""
    return [first + diff * i for i in range(n)]


# ── 关1：首行 3 根，每行多 1 根，共 8 行 ──
r1 = rows(3, 1, 8)
chk("关1 逐行", r1, [3, 4, 5, 6, 7, 8, 9, 10])
chk("关1 末行", r1[-1], 10)
chk("关1 逐根累加", sum(r1), 52)
chk("关1 公式 (3+10)×8÷2", (3 + 10) * 8 // 2, 52)

# ── 关2：首行 5、末行 21、每行多 2 → 行数与总数 ──
n2 = (21 - 5) // 2 + 1
chk("关2 行数 (21-5)÷2+1", n2, 9)
r2 = rows(5, 2, n2)
chk("关2 末行回验", r2[-1], 21)
chk("关2 逐根累加", sum(r2), 117)
chk("关2 公式 (5+21)×9÷2", (5 + 21) * 9 // 2, 117)
chk("关2 忘+1 的错答（教学要点）", (21 - 5) // 2, 8)   # 学生易答 8 行

# ── 关3：首行 4，每行多 3，正好用完 175 根 → 行数、末行 ──
sols = []
for n in range(1, 60):
    s = sum(rows(4, 3, n))
    if s == 175:
        sols.append((n, rows(4, 3, n)[-1]))
chk("关3 解的个数（唯一才算好题）", len(sols), 1)
chk("关3 行数/末行", sols[0], (10, 31))
chk("关3 逐根累加回验", sum(rows(4, 3, 10)), 175)
chk("关3 公式 (4+31)×10÷2", (4 + 31) * 10 // 2, 175)
print("      邻近行数试算：n=9 →", sum(rows(4, 3, 9)), "／ n=11 →", sum(rows(4, 3, 11)))

# ── 关4（年份压轴）：2026 行，第 n 行 n 根 → 首尾配对求总数 ──
Y = 2026
chk("关4 每对的和 1+2026", 1 + Y, 2027)
chk("关4 配对数 2026÷2", Y // 2, 1013)
chk("关4 2026 是偶数（能两两配完，无落单行）", Y % 2, 0)
# 逐对核对：第 k 行 + 第 (2026+1-k) 行 恒为 2027
pairs = {(k + (Y + 1 - k)) for k in range(1, Y // 2 + 1)}
chk("关4 每一对都相等", pairs, {2027})
total_pair = 2027 * 1013
chk("关4 配对法总数", total_pair, 2053351)
chk("关4 逐行累加回验", sum(range(1, Y + 1)), 2053351)
chk("关4 梯形公式回验 (1+2026)×2026÷2", (1 + Y) * Y // 2, 2053351)
# 分配律拆解（四年级手算路径）
chk("关4 拆解 2027×1000", 2027 * 1000, 2027000)
chk("关4 拆解 2027×13", 2027 * 13, 26351)
chk("关4 拆解合计", 2027000 + 26351, 2053351)

# ── 同构核对：等差求和 ≡ 梯形面积公式 ──
first, last, cnt = 5, 21, 9
chk("同构 (首+末)×项数÷2 == (上底+下底)×高÷2",
    (first + last) * cnt // 2, (first + last) * cnt // 2)
print("      首项↔上底 5 ｜ 末项↔下底 21 ｜ 项数↔高 9 → 都得 117")

print("\n汇总:", "ALL PASS" if all(OK) else f"有 {OK.count(False)} 处 FAIL")
