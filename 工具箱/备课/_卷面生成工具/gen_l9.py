def blank_grid(cols, rows, cell=40):
    """空方格纸（学生作图用），浅灰细线。"""
    ss = 3
    w, h = cols * cell * ss + 2 * ss, rows * cell * ss + 2 * ss
    im = Image.new('RGB', (w, h), 'white')
    dr = ImageDraw.Draw(im)
    for r in range(rows):
        for c in range(cols):
            x0, y0 = c * cell * ss + ss, r * cell * ss + ss
            dr.rectangle([x0, y0, x0 + cell * ss, y0 + cell * ss],
                         outline=(175, 175, 175), width=1 * ss)
    return im.resize((w // ss, h // ss), Image.LANCZOS)


def views_fig(cells, keys=('front', 'left', 'top'), name='x.png'):
    v = c3.views_of(cells)
    labs = {'front': '从前面看', 'left': '从左面看', 'top': '从上面看'}
    imgs = [c3.draw_view(v[k]) for k in keys]
    return save(c3.hstack(imgs, labels=[labs[k] for k in keys]), name)


