/**
 * 判据沉淀的数据（mock）。
 *
 * 🔴 这份数据沉淀的是**产线自己的判断经验**，不是学生的错。
 *    每一条都来自一次真实事故或一次用户拍板 —— 录题怎么拆、批改怎么判、出题怎么防坑。
 *    所以这里**一条都不许现编**：编出来的「经验」注入给 agent，比没有更坏。
 *
 * 🔴 放在页面目录而不是 `@/mock`：判据沉淀是本页自留数据，`@/mock/types.ts` 是地基工的正本。
 *    等判据接真数据（agent 沉淀写入）时再由地基工提到 `@/mock` 去。
 *    先例 = `pages/export-preview/templates.ts`。
 *
 * 🔴 date 的口径 = **这条判据最后一次拍板/变更的日期**；废止条上的 date = 废止那天。
 *    日期取自各条对应的记忆正本 / `订阅特训/_产线/变更记录-*.md` / PRD 交付日，不是估的。
 */

/** 判据挂在哪条产线上（挂产线，不挂考点 —— 挂考点的是错因管理） */
export type CriterionLine = '录入' | '批改' | '出题'

/** 现行 = 注入给 agent；废止 = 不注入，但留档可查（推翻过什么，本身也是经验） */
export type CriterionStatus = '现行' | '废止'

export interface Criterion {
  id: string
  line: CriterionLine
  /** 什么场景触发这条判据（agent 干到哪一步会撞上它） */
  scene: string
  /** 怎么判（判据正文，就是注入给 agent 的那句话） */
  rule: string
  /** 为什么这么判。🔴 只写查得到出处的，查不到就不写 —— 空着比编一个理由强 */
  why?: string
  /** 来源：哪次事故 / 哪次拍板 / 哪份正本 */
  sourceRef: string
  /** 最后一次拍板或变更的日期（废止条 = 废止日） */
  date: string
  status: CriterionStatus
  /** 被哪条替代（只有废止条才有，替代链就靠它串） */
  supersededBy?: string
}

