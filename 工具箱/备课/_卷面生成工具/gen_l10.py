def qhtml(n, q, ans, spacer):
    h = [f'<div class="q"><span class="no">{n}．</span><span class="star">{"★" * q["d"]}</span>{q["stem"]}</div>']
    if q.get('fig'):
        h.append(q['fig'])
    if ans:
        if q.get('ansfig'):
            h.append(q['ansfig'])
        h.append(f'<div class="ansbox"><p><span class="lab">【答案】</span>{q["answer"]}</p>'
                 f'<p><span class="lab">【解析】</span>{q["analyze"]}</p></div>')
    else:
        h.append(f'<div class="{spacer}"></div>')
    return h


